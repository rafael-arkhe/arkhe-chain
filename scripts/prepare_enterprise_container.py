"""Assemble a credential-free, explicit source context for the Enterprise OCI build."""
import hashlib,json,shutil,sys,tomllib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DEST=ROOT/'ops/local/enterprise-container-context'
EXCLUDED={'target','node_modules','.git','.next','__pycache__','output','credentials.json','accounts.json'}

def copy_file(relative):
    source=ROOT/relative
    target=DEST/relative
    target.parent.mkdir(parents=True,exist_ok=True)
    shutil.copy2(source,target)

def copy_tree(relative):
    source=ROOT/relative
    for path in source.rglob('*'):
        parts=path.relative_to(source).parts
        if any(part in EXCLUDED or part.startswith('.env') for part in parts):continue
        if path.is_file() and not path.is_symlink() and path.suffix not in {'.pem','.key','.sqlite'}:
            copy_file(path.relative_to(ROOT))

def main():
    global DEST
    if len(sys.argv)>1:
        DEST=(ROOT/sys.argv[1]).resolve()
        if not DEST.is_relative_to(ROOT/'ops/local'):
            raise SystemExit('Build context must stay inside ops/local')
    if DEST.exists():
        raise SystemExit(f'Context already exists: {DEST}. Use a new explicit context path or inspect/remove this generated directory before rebuilding.')
    DEST.mkdir(parents=True)
    for name in ['package.json','pnpm-lock.yaml','pnpm-workspace.yaml','Cargo.toml','Cargo.lock','config/architecture.json']:
        copy_file(name)
    for member in tomllib.loads((ROOT/'Cargo.toml').read_text())['workspace']['members']:
        copy_tree(member)
    for directory in ['apps/arkhe-intra','storage/sql/migrations','specs/mmr']:
        copy_tree(directory)
    # Portable WASM generated by the existing verifier build; required and hashed below.
    for name in ['arkhe_verify_wasm.js','arkhe_verify_wasm_bg.wasm','package.json']:
        path=Path('verification/crates/arkhe-verify-wasm/pkg')/name
        if not (ROOT/path).is_file():raise SystemExit('Run pnpm verify:wasm first: '+str(path))
        copy_file(path)
    for name in ['e01_solana_transport.mjs','e02_verify.mjs','e02_mmr.mjs','e02_memo_commitment.mjs','enterprise_container_entry.mjs','enterprise_server_supervisor.mjs']:
        copy_file(Path('scripts')/name)
    shutil.copy2(ROOT/'apps/arkhe-intra/Dockerfile',DEST/'Dockerfile')
    manifest={p.relative_to(DEST).as_posix():hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(DEST.rglob('*')) if p.is_file()}
    (DEST/'context-manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
    print(f'Prepared {len(manifest)} files, {sum(p.stat().st_size for p in DEST.rglob("*") if p.is_file())} bytes: {DEST}')

if __name__=='__main__':main()
