import test from 'node:test';
import assert from 'node:assert/strict';
import { channels, gateLine, groupOf, groups, layerBody, layerLine, layers, limits, paneBody, proposalError, runScreen, screenByPath, screens, stores } from '../lib/bench.mjs';

test('a bancada segura o efeito e rejeita a decisão', () => {
  assert.equal(gateLine(false), 'Reject · regra em falta');
  assert.equal(gateLine(true), 'Reject · paragem de emergência');
  assert.match(paneBody('gate', true), /Nenhum processo recebe sinal/);
  assert.match(paneBody('effect', false), /Unmediated/);
  assert.equal(channels.every(([, release]) => release === 'Held'), true);
  assert.equal(proposalError('curta'), 'Escreva uma proposta entre 10 e 2000 caracteres.');
  assert.equal(proposalError('Acrescentar um teste de plano vazio.'), '');
  assert.equal(layerLine('preempt', false), 'NotImplemented');
  assert.match(layerBody('preempt', false), /Nenhum processo recebe sinal/);
  assert.equal(layerLine('eval', false), 'not scored');
  assert.match(layerBody('formal', false), /nenhum teorema foi aceite/);
  assert.equal(stores.every(([, release]) => release === 'Unavailable'), true);
  assert.deepEqual(limits.map(([id]) => id), ['preempt', 'resume', 'formal', 'eval']);
  assert.equal(layers.some(layer => layer.line === 'PASS'), false);
  assert.equal(paneBody('effect', false), layerBody('effect', false));
  assert.equal(screens.length, 13);
  assert.equal(screens.every(screen => runScreen(screen.id, false)?.releasesEffect === false), true);
  assert.equal(runScreen('gate', true)?.fields.find(([label]) => label === 'Decisão')?.[1], 'Reject');
  assert.equal(runScreen('gate', true)?.fields.find(([label]) => label === 'Sinal')?.[1], 'não');
  assert.equal(runScreen('effect', false)?.fields.filter(([, value]) => String(value).startsWith('Held')).length, 4);
  assert.equal(runScreen('resume', false)?.fields.find(([label]) => label === 'É evidência')?.[1], 'não');
  assert.equal(runScreen('consensus', false)?.fields.find(([label]) => label === 'É durabilidade')?.[1], 'não');
  assert.equal(runScreen('eval', false)?.fields.find(([label]) => label === 'Nota')?.[1], 'not scored');
  assert.equal(runScreen('formal', false)?.fields.find(([label]) => label === 'Teorema aceite')?.[1], 'não');
  assert.equal(runScreen('receipt', false)?.fields.find(([label]) => label === 'Lança processo')?.[1], 'não');
  assert.equal(runScreen('intent', false)?.fields.find(([label]) => label === 'WER')?.[1], 'não');
  assert.equal(screenByPath('ausente'), null);
  assert.equal(screenByPath('consenso')?.fn, 'lerConsenso');
  const grouped = groups.flatMap(group => group.ids);
  assert.equal(new Set(grouped).size, screens.length);
  assert.deepEqual(grouped.slice().sort(), screens.map(screen => screen.id).sort());
  assert.equal(groupOf('gate')?.title, 'Decisão');
  assert.equal(groupOf('consensus')?.title, 'Fora deste caminho');
});
