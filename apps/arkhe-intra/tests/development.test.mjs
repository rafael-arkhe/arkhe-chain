import test from 'node:test';
import assert from 'node:assert/strict';
import { generateKeyPairSync, sign, createHash } from 'node:crypto';
import { mkdtempSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
process.env.ARKHE_INTRA_DATA_DIR = mkdtempSync(join(tmpdir(), 'arkhe-development-test-'));
delete process.env.ARKHE_SANDBOX_IMAGE;
const { catalog, overview, validateProposal, sourceSnapshot, sandboxArguments, startRun, reviewChallenge, decideRun, readRun, rejectRun } = await import('../lib/development.mjs');
const { db, auditIntegrity } = await import('../lib/store.mjs');
const pair = generateKeyPairSync('ed25519');
const owner = {id:'test-owner', role:'owner', publicKey:pair.publicKey.export({type:'spki',format:'pem'})};
const module = catalog().find(row => row.id === 'arkhe-agent');
test('development boundaries: catalog, source isolation and strict proposals', async () => {
  const architecture = JSON.parse(readFileSync(new URL('../../../config/architecture.json', import.meta.url), 'utf8'));
  assert.deepEqual(catalog().map(row => row.path), architecture.rust_members);
  assert.equal(catalog().filter(row => row.boundary === 'reference').length,7);
  const bridge = catalog().find(row => row.path === 'integrations/arkhe-python-runtime/bridge');
  assert.equal(bridge.id, 'arkhe-python-bridge');
  assert.equal(bridge.test, 'cargo test --locked --offline -p arkhe-python-bridge');
  assert.throws(() => overview({role:'author'}), /governança/);
  assert.throws(() => validateProposal({summary:'x',files:[{path:'../../ops/local/intra/accounts.json',content:'x'}]},module));
  for (const path of ['cognition/arkhe-agent/src/../lib.rs','cognition/arkhe-agent/src/a\\b.rs','kernel/arkhe-core/src/lib.rs','cognition/arkhe-agent/Cargo.toml','cognition/arkhe-agent/src/-x.rs']) {
    if (path.endsWith('/-x.rs')) continue;
    assert.throws(() => validateProposal({summary:'x',files:[{path,content:'x'}]},module));
  }
  const proposal = {summary:'x',files:[{path:'cognition/arkhe-agent/src/lib.rs',content:'// test'}]};
  assert.deepEqual(validateProposal(proposal,module),proposal);
  assert.throws(() => validateProposal({...proposal, files:[...proposal.files,...proposal.files]},module));
  const destination = mkdtempSync(join(tmpdir(),'arkhe-snapshot-test-'));
  const baseline = sourceSnapshot(destination);
  assert.ok(baseline['cognition/arkhe-agent/src/lib.rs']);
  assert.ok(baseline['integrations/arkhe-python-runtime/bridge/Cargo.toml']);
  assert.ok(!Object.keys(baseline).some(path => path.startsWith('ops/') || path.endsWith('.pem') || path.includes('node_modules')));
  assert.equal(readFileSync(join(destination,'Cargo.lock'),'utf8'),readFileSync(new URL('../../../Cargo.lock',import.meta.url),'utf8'));
  assert.throws(() => sandboxArguments('rust:latest','n','C:/snapshot',module));
  const args = sandboxArguments('sha256:'+'a'.repeat(64),'n','C:/snapshot',module);
  for (const flag of ['--network=none','--read-only','--cap-drop=ALL','--security-opt=no-new-privileges','--pull=never','--user=10001:10001','--pids-limit=128']) assert.ok(args.includes(flag));
  assert.ok(args.includes('C:/snapshot:/input:ro'));
  await assert.rejects(startRun(owner,{moduleId:module.id,objective:'Add a regression test'}),/ARKHE_SANDBOX_IMAGE/);
  assert.equal(overview(owner).runs.length,0);
});
test('development decisions bind baseline, proposal and evidence; no implicit incorporation', () => {
  overview(owner);
  const sha = value => createHash('sha256').update(JSON.stringify(value)).digest('hex');
  const run = {id:'11111111-1111-4111-8111-111111111111',moduleId:module.id,state:'passed',baseline:{file:'hash'},proposal:{summary:'test',files:[]},image:'sha256:'+'a'.repeat(64),exitCode:0,log:'test result: ok. 1 passed',authority:false};
  run.baselineDigest=sha(run.baseline); run.proposalDigest=sha(run.proposal);
  run.evidenceDigest=sha({baselineDigest:run.baselineDigest,proposalDigest:run.proposalDigest,image:run.image,exitCode:run.exitCode,log:run.log});
  db().prepare('INSERT INTO development_runs(id,value) VALUES(?,?)').run(run.id,JSON.stringify(run));
  const challenge = reviewChallenge(owner,run.id);
  const signature = sign(null,Buffer.from(challenge.statement),pair.privateKey).toString('base64');
  db().prepare('UPDATE development_runs SET value=? WHERE id=?').run(JSON.stringify({...run,evidenceDigest:'tampered'}),run.id);
  assert.throws(() => decideRun(owner,run.id,{signature}),/alteradas|Assinatura/);
  db().prepare('UPDATE development_runs SET value=? WHERE id=?').run(JSON.stringify(run),run.id);
  assert.equal(decideRun(owner,run.id,{signature}).state,'approved');
  assert.equal(readRun(owner,run.id).authority,false);
  assert.throws(() => decideRun(owner,run.id,{signature}));
  assert.throws(() => rejectRun(owner,run.id));
  assert.equal(auditIntegrity(),true);
});
