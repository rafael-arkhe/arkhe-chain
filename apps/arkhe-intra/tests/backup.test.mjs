import test from 'node:test';
import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import { mkdtempSync, writeFileSync, readFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { createBackup, restoreBackup, verifyDatabase } from '../scripts/backup.mjs';
const directory=mkdtempSync(join(tmpdir(),'arkhe-backup-')),source=join(directory,'source');
const {mkdirSync}=await import('node:fs');mkdirSync(source);
test('online SQLite backup includes WAL, isolated restore clears sessions, and rejects corruption/overwrites',async()=>{
  const database=new DatabaseSync(join(source,'intra.sqlite'));
  database.exec("PRAGMA journal_mode=WAL;CREATE TABLE events(seq INTEGER PRIMARY KEY,value TEXT,previous TEXT,hash TEXT);CREATE TABLE sessions(hash TEXT PRIMARY KEY);CREATE TABLE documents(id TEXT PRIMARY KEY,value TEXT);INSERT INTO documents VALUES('preserved','{}');INSERT INTO sessions VALUES('old-token');");
  writeFileSync(join(source,'accounts.json'),'[{"id":"synthetic-owner"}]');writeFileSync(join(source,'owner.private.pem'),'NEVER COPY');
  const destination=join(directory,'snapshot');
  assert.equal((await createBackup(source,destination)).status,'verified');
  database.exec("INSERT INTO documents VALUES('after-snapshot','{}')");database.close();
  const restored=join(directory,'restored');assert.equal(restoreBackup(destination,restored).status,'restored');
  const check=new DatabaseSync(join(restored,'intra.sqlite'));
  assert.equal(check.prepare('SELECT count(*) AS n FROM documents').get().n,1);assert.equal(check.prepare('SELECT count(*) AS n FROM sessions').get().n,0);check.close();
  assert.throws(()=>readFileSync(join(destination,'owner.private.pem')));
  assert.throws(()=>restoreBackup(destination,restored));
  await assert.rejects(createBackup(source,join(source,'nested')));
  writeFileSync(join(destination,'accounts.json'),'tampered');assert.throws(()=>restoreBackup(destination,join(directory,'bad-restore')),/checksum/);
  const altered=new DatabaseSync(join(restored,'intra.sqlite'));altered.exec("INSERT INTO events VALUES(1,'{}','invalid','invalid')");altered.close();assert.throws(()=>verifyDatabase(join(restored,'intra.sqlite')),/Audit chain/);
  const corrupt=join(directory,'corrupt.sqlite');writeFileSync(corrupt,'not sqlite');assert.throws(()=>verifyDatabase(corrupt));
  const brokenStart=join(directory,'broken-start');mkdirSync(brokenStart);writeFileSync(join(brokenStart,'intra.sqlite'),'not sqlite');
  assert.throws(()=>execFileSync(process.execPath,['--input-type=module','-e','const {db}=await import(process.argv[1]);db();',new URL('../lib/store.mjs',import.meta.url).href],{env:{...process.env,ARKHE_INTRA_DATA_DIR:brokenStart},stdio:'pipe'}),/SQLite integrity check failed/);
});
